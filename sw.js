self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll([...APP_SHELL, './manifest.webmanifest', './icons/badoc-hub-spx-round-v3-192.png', './icons/badoc-hub-spx-round-v3-512.png']);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith('badoc-hub-pwa-') && key !== CACHE_NAME).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  // Only cache the GitHub Pages app itself. SPX/API requests are left untouched.
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      try {
        const response = await fetch(request);
        if (response && response.ok) await cache.put(request, response.clone());
        return response;
      } catch (_) {
        return (await cache.match(request)) || (await cache.match('./index.html')) || Response.error();
      }
    })());
    return;
  }

  // Hash-stamped assets (?v=...) never change for a given URL -> cache-first.
  // Anything else same-origin (icons, manifest, unstamped files) -> stale-while-revalidate.
  const stamped = url.searchParams.has('v');
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    if (cached && stamped) return cached;
    const refresh = fetch(request).then(async response => {
      if (response && response.ok) await cache.put(request, response.clone());
      return response;
    });
    if (cached) { refresh.catch(() => {}); return cached; }
    try { return await refresh; } catch (_) { return Response.error(); }
  })());
});
